#String Methods

#Upper to lower
capital_city ="DELHI "
print(capital_city.lower())

#Lower to upper
print(capital_city.upper())

#strip(Removes leading and trailing spaces from a string)
print(capital_city.strip()*3)

#Replace(Relplaces a substring with another string)
print(capital_city.replace("DELHI", "Karnataka"))

#Length of a string
print(len(capital_city))




